"""run_tests.py

Runs the pytest suite and regenerates ``reports/test_report.md`` and
``reports/pytest_raw.txt`` from the actual current run.

Run from the project root:

    python run_tests.py
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from src.config import REPORTS_DIR

RAW_PATH = REPORTS_DIR / "pytest_raw.txt"
REPORT_PATH = REPORTS_DIR / "test_report.md"

MODULE_TITLES = [
    ("test_business_analysis", "Business Analysis"),
    ("test_dashboard",         "Dashboard data layer & artefacts"),
    ("test_data_loader",       "Data loader"),
    ("test_predictive_alerts", "Predictive alerts"),
    ("test_recommendations",   "Recommendations"),
    ("test_sales_prediction",  "Sales prediction"),
]


def run_pytest() -> str:
    cmd = [sys.executable, "-m", "pytest", "tests/", "-v"]
    print(f"Running: {' '.join(cmd)}")
    proc = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    raw = proc.stdout + "\n" + proc.stderr
    RAW_PATH.write_text(raw, encoding="utf-8")
    print(f"Wrote raw pytest output -> {RAW_PATH.relative_to(ROOT)}")
    return raw


def parse_report(raw: str) -> str:
    total_passed = raw.count(" PASSED")
    total_failed = raw.count(" FAILED")
    m = re.search(r"in ([\d.]+)s", raw)
    duration = m.group(1) if m else "?"

    lines: list[str] = []
    lines.append("# Test Report — AI-Based Business Prediction and Recommendation System\n")
    lines.append("Generated by `pytest` against the real project source and the real "
                 "`data/superstore.csv` dataset.\n")
    lines.append(f"**Command:** `python -m pytest tests/ -v`  ")
    lines.append(f"**Platform:** {sys.platform}, Python {sys.version.split()[0]}  ")
    lines.append(f"**Total tests:** {total_passed + total_failed}  ")
    lines.append(f"**Passed:** {total_passed}  ")
    lines.append(f"**Failed:** {total_failed}  ")
    lines.append(f"**Duration:** {duration}s  ")
    lines.append(f"**Result:** {'ALL PASSED' if total_failed == 0 else 'FAILURES PRESENT'}\n")
    lines.append("---\n")

    for fname, title in MODULE_TITLES:
        cases: list[tuple[str, str]] = []
        for line in raw.splitlines():
            if f"tests/{fname}.py::" in line:
                try:
                    testname = line.split("::")[1].split(" ")[0]
                except IndexError:
                    testname = "?"
                if " PASSED" in line:
                    cases.append((testname, "PASSED"))
                elif " FAILED" in line:
                    cases.append((testname, "FAILED"))
        passed = sum(1 for _, r in cases if r == "PASSED")
        failed = sum(1 for _, r in cases if r == "FAILED")
        lines.append(f"## {fname} ({passed} passed, {failed} failed)\n")
        lines.append(f"**Module covered:** {title}\n")
        lines.append("| # | Test | Result |")
        lines.append("|---|------|--------|")
        for i, (test, res) in enumerate(cases, start=1):
            lines.append(f"| {i} | `{test}` | {res} |")
        lines.append("")

    lines.append("---\n")
    lines.append("## Reproducing\n")
    lines.append("```bash")
    lines.append("cd AI_Business_Prediction_System")
    lines.append("python -m pytest tests/ -v")
    lines.append("```\n")
    lines.append("Raw pytest output is also persisted at `reports/pytest_raw.txt`.")
    return "\n".join(lines)


def main() -> int:
    raw = run_pytest()
    REPORT_PATH.write_text(parse_report(raw), encoding="utf-8")
    print(f"Wrote markdown report  -> {REPORT_PATH.relative_to(ROOT)}")
    print(f"\nSummary: {'ALL PASSED' if raw.count(' FAILED') == 0 else 'FAILURES'}"
          f" ({raw.count(' PASSED')} passed, {raw.count(' FAILED')} failed)")
    return 0 if raw.count(" FAILED") == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
